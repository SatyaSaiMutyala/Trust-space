/** Dropdown values. Fixed ones come from the API's own rules (resources/config.js); owners, properties and property
 *  uses also include what is already in the database. */
export async function lists(models) {
  const [owners, properties, types] = await Promise.all([
    models.owners.find({}, { name: 1, pan: 1 }).sort({ name: 1 }).lean(),
    models.properties.find({}, { code: 1, name: 1 }).sort({ code: 1 }).lean(),
    models.properties.distinct('type'),
  ])
  return {
    ownerKind: byPath.owners.enums.kind,
    acctType: ['Savings', 'Current'],
    propertyType: [...new Set([...PROPERTY_TYPES, ...types.filter(Boolean)])],
    propertyStatus: byPath.properties.enums.status,
    leaseStatus: byPath.leases.enums.status,
    payTiming: byPath.leases.enums.payTiming,
    gstMode: byPath.leases.enums.gstMode,
    escType: ['Compound', 'Simple'],
    escFrom: ['Lease start', 'Rent commencement'],
    maintType: ['Fixed monthly', 'Actuals', 'Included in rent', 'None'],
    elec: ['Actuals (sub-meter)', 'Direct DISCOM bill (TDPL)', 'Included in rent', 'Fixed monthly'],
    yesNo: YES_NO,
    owners: owners.map(o => ownerLabel(o)),
    properties: properties.map(p => propertyLabel(p)),
  }
}

/** How an owner / property shows in a dropdown (and is recognised when read back). */
export const ownerLabel = o => o.pan ? `${o.name} · ${o.pan}` : o.name
export const propertyLabel = p => `${p.code} · ${p.name}`
