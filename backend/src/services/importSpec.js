/*
 * The Excel import (owners, properties, leases): which columns each sheet has, which are required, and where the
 * dropdown values come from. The same spec builds the downloadable template (controllers/importer.js → template) and
 * reads a filled-in file back (→ preview / commit), so the two can never drift apart.
 *
 *   key        field on the record
 *   label      column header in the sheet (matched case-insensitively when reading)
 *   required   the cell may not be blank
 *   kind       text (default) | number | date | bool | list
 *   list       name of a dropdown list (see lists() below); `loose` lists accept values that are not in the list
 *              (owner / property references, where the record may be a new row in the same file)
 *   upper      stored in capitals (PAN, GSTIN, IFSC, site code)
 *   def        value used when the cell is blank
 *   note       shown as a comment on the header cell
 *   width      column width in the template
 */
