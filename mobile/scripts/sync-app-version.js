#!/usr/bin/env node
/* Writes src/config/appVersion.js from the native version numbers, so the force-update check always compares the
   version that was actually built:
     Android  android/app/build.gradle      versionName / versionCode
     iOS      ios/TruSpace.xcodeproj         MARKETING_VERSION / CURRENT_PROJECT_VERSION
   Runs before Metro and before every native build (npm scripts, a Gradle task and an Xcode build phase), so there is
   nothing to update by hand: bump the native numbers and the file follows. `--check` only verifies the file is current. */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const gradle = read('android/app/build.gradle');
const pbx = read('ios/TruSpace.xcodeproj/project.pbxproj');
const pick = (src, re, what) => { const m = src.match(re); if (!m) throw new Error(`sync-app-version: could not find ${what}`); return m[1]; };

const android = { version: pick(gradle, /versionName\s+"([^"]+)"/, 'versionName in android/app/build.gradle'), build: pick(gradle, /versionCode\s+(\d+)/, 'versionCode in android/app/build.gradle') };
const ios = { version: pick(pbx, /MARKETING_VERSION = ([\d.]+);/, 'MARKETING_VERSION in the Xcode project'), build: pick(pbx, /CURRENT_PROJECT_VERSION = (\d+);/, 'CURRENT_PROJECT_VERSION in the Xcode project') };
const pkg = JSON.parse(read('app.json'));

const out = `/* GENERATED by scripts/sync-app-version.js — do not edit. Bump the native version numbers instead:
   Android: android/app/build.gradle versionName / versionCode · iOS: Xcode target → General → Version / Build. */
import { Platform } from 'react-native';

export const ANDROID_VERSION = '${android.version}';
export const ANDROID_BUILD = ${android.build};
export const IOS_VERSION = '${ios.version}';
export const IOS_BUILD = ${ios.build};
/** This build's own version, as the stores show it. */
export const APP_VERSION = Platform.OS === 'ios' ? IOS_VERSION : ANDROID_VERSION;
export const APP_BUILD = Platform.OS === 'ios' ? IOS_BUILD : ANDROID_BUILD;
export const ANDROID_PACKAGE_ID = 'com.app.truspace';
export const IOS_BUNDLE_ID = 'com.app.truspace';
export const APP_NAME = '${pkg.displayName || pkg.name || 'TruSpace'}';
export const PLAY_STORE_URL = \`https://play.google.com/store/apps/details?id=\${ANDROID_PACKAGE_ID}\`;
`;
const target = path.join(root, 'src/config/appVersion.js');
const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
if (process.argv.includes('--check')) {
  if (current !== out) { console.error('src/config/appVersion.js is out of date — run: node scripts/sync-app-version.js'); process.exit(1); }
  process.exit(0);
}
if (current !== out) { fs.writeFileSync(target, out); console.log(`appVersion.js updated: Android ${android.version} (${android.build}), iOS ${ios.version} (${ios.build})`); }
